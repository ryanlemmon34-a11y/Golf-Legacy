def q(xs, p):
    xs = sorted(xs)
    if not xs:
        return float('nan')
    i = (len(xs) - 1) * p
    lo, hi = math.floor(i), math.ceil(i)
    return xs[lo] + (xs[hi] - xs[lo]) * (i - lo)


def med(xs):
    return q(xs, 0.5)


def f1(x, nd=1):
    return '-' if x is None or (isinstance(x, float) and math.isnan(x)) else f'{x:.{nd}f}'


def corr(xs, ys):
    if len(xs) < 3:
        return float('nan')
    mx, my = st.fmean(xs), st.fmean(ys)
    sxy = sum((a - mx) * (b - my) for a, b in zip(xs, ys))
    sx = math.sqrt(sum((a - mx) ** 2 for a in xs))
    sy = math.sqrt(sum((b - my) ** 2 for b in ys))
    return sxy / (sx * sy) if sx and sy else float('nan')


def at(e, age):
    t = e.get('traj')
    if not t or age < e['age']:
        return None
    return t[age - e['age']]


def years_at_or_above(e, lvl):
    return sum(1 for v in e['traj'] if v >= lvl) if e.get('traj') else 0


def peak_of(e):
    t = e['traj']
    m = max(t)
    return m, e['age'] + t.index(m)


