def deltas(by_arm, groups, ages, only_touched):
    out, js = [], {}
    base = {e['key']: e for e in by_arm['A0'] if e.get('traj')}
    for gname, gfn in groups:
        for arm in ARMS[1:]:
            pairs = [(e, base[e['key']]) for e in by_arm[arm]
                     if e.get('traj') and e['key'] in base and gfn(e) and (not only_touched or touched(e, arm))]
            if not pairs:
                continue
            cells = []
            for a in ages:
                ds = [at(x, a) - at(y, a) for x, y in pairs if at(x, a) is not None and at(y, a) is not None]
                cells.append(f'{f1(med(ds), 2)} ({f1(q(ds, .1), 2)}, {f1(q(ds, .9), 2)})' if ds else '-')
                js.setdefault(arm, {}).setdefault(gname, {})[a] = {'n': len(ds), 'median': med(ds) if ds else None}
            dm = [max(x['traj']) - max(y['traj']) for x, y in pairs]
            cells.append(f'{f1(med(dm), 2)} ({f1(q(dm, .1), 2)}, {f1(q(dm, .9), 2)})')
            out.append(f'| {LABEL[arm]} | {gname} | {len(pairs):,} | ' + ' | '.join(cells) + ' |')
    return out, js


