def hist_stats(gen, prefix):
    """Median, 10th percentile and shares <= 3 / <= 5 from a 0.5-point headroom histogram."""
    bins = sorted((float(k.split(':')[1]), v) for k, v in gen.items() if k.startswith(prefix + ':'))
    n = sum(v for _, v in bins)
    if not n:
        return None
    def quant(p):
        c = 0
        for b, v in bins:
            c += v
            if c >= p * n:
                return b + 0.25
        return bins[-1][0]
    le = lambda h: sum(v for b, v in bins if b + 0.5 <= h + 1e-9)
    return {'n': n, 'median': quant(0.5), 'p10': quant(0.1), 'le3': le(3) / n, 'le5': le(5) / n}


