"""When each tour's standings lock, and when the rights and cards they decide take effect -- worked out from the
calendar and the card rules themselves, for both calendar versions (docs/STANDINGS_AND_RIGHTS.md is this
script's output, so the document cannot drift from the code: tests/test_qualification_views.py checks it).

    python tools/standings_calendar.py > docs/STANDINGS_AND_RIGHTS.md
"""
from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from golfsim import cards as C                                    # noqa: E402
from golfsim import schedule as SCH                               # noqa: E402
from golfsim.calendar import TOUR_BY_KEY, WorldCalendar                  # noqa: E402
from golfsim.season import PREMIER_TOURS                          # noqa: E402

YEAR = 2030                                                       # (any season: the weeks repeat every year)


def money_weeks(version):
    """{money list: sorted weeks of the events that count for it} as season.pay_out credits them: an event counts
    for its own tour; a major for every Premier tour; every major and tier-1 event for the combined Premier list."""
    cal = WorldCalendar(YEAR, version)
    out = defaultdict(list)
    for ed in cal.editions(YEAR):
        s = ed.series
        if s.kind == 'qualifying':
            continue
        keys = [s.tour] if s.tour in TOUR_BY_KEY else []
        if s.kind == 'major':
            keys = list(PREMIER_TOURS)
        if s.tier <= 1:
            keys.append('PREMIER')
        for k in keys:
            out[k].append(ed.week)
    return {k: sorted(v) for k, v in out.items()}


def decides(tour):
    t = TOUR_BY_KEY[tour]
    if tour in PREMIER_TOURS:
        extra = {'PT_EUROPE': 'top 10 also move up to Premier Tour Americas',
                 'PT_ASIA_PACIFIC': 'top 5 also move up to Premier Tour Americas'}.get(tour)
        return ('membership by the combined Premier money list (below); ' + extra) if extra else \
            'membership by the combined Premier money list (below)'
    if t.tier == 2:
        n, to = C.CHALLENGER_TO_PREMIER.get(tour, (0, None))
        up = f'top {n} move up to {TOUR_BY_KEY[to].name}; ' if n else ''
        return up + f'at least {C.CHALLENGER_KEEP:.0%} of members keep their card (more if the tour would be short)'
    if t.tier == 3:
        return (f'top {C.REGIONAL_UP} move up to their home Challenger tour; at least {C.REGIONAL_KEEP:.0%} keep '
                'their card')
    if t.tier == 4:
        return (f'top {C.MINI_UP_CHALLENGER} move up to their home Challenger tour, the next {C.MINI_UP_REGIONAL} to '
                'their Regional tour; every member keeps a mini-tour place')
    return 'no cards (amateur, college or club-professional circuit)'


def doc():
    out = ['# Standings locks, and when rights and cards take effect', '',
           'Generated by `tools/standings_calendar.py` from the calendar (`golfsim/schedule.py`, '
           '`golfsim/calendar.py`) and the card rules (`golfsim/cards.py`); regenerate it after changing either. '
           'Weeks are the calendar\'s weeks 1-52; a season ends after week 52.', '',
           '## How the engine uses standings', '',
           '- **Money lists** accumulate as prize money is paid: an event counts for its own tour\'s list; a major for '
           'every Premier tour\'s list; every major and tier-1 (Premier) event for the **combined Premier list**. '
           'A list is final (locked) after the last event that counts for it.',
           '- **Cards** are decided once, at the end of the season (after week 52, `cards.apply_cards`), from the '
           'final money lists, the season\'s Q-School finals and winners\' exemptions. They take effect from **week 1 '
           'of the next season**: nobody changes tour during a season.',
           f'- **Premier Tour**: the top {C.PREMIER_KEEP} of the combined Premier list keep a card; winners keep or '
           'earn one through their exemption (a major in the five seasons before, a Premier event in the two '
           'before); a non-member whose Premier money beats the last member to keep a card earns one.',
           '- **Major places** from last season (champions, top finishers, final standings, the amateur award, '
           'amateur titles) are worked out at the end of that season (`qualification.secured_places`) and kept in '
           'the rights ledger for the target edition. Places decided by a ranking or points list published during '
           'the major\'s own season are decided only by the list published at the cut-off (below): a projection '
           'is never a place.', '']
    for v in ('v1', 'v2'):
        sp = SCH.spec(v)
        mw = money_weeks(v)
        out += [f'## {sp.label} (`{v}`)', '',
                '| Money list | Tier | Events counting | First week | Locks after week | What it decides (at the season\'s end; effective week 1 next season) |',
                '|---|---|---|---|---|---|']
        for key in ['PREMIER'] + sorted((k for k in TOUR_BY_KEY if k in mw), key=lambda k: (TOUR_BY_KEY[k].tier, k)):
            weeks = mw.get(key)
            if not weeks:
                continue
            if key == 'PREMIER':
                name, tier, what = 'Combined Premier list (majors and Premier events)', 1, \
                    f'Premier cards: the top {C.PREMIER_KEEP} keep theirs (plus winners\' exemptions)'
            else:
                name, tier, what = TOUR_BY_KEY[key].name, TOUR_BY_KEY[key].tier, decides(key)
            out.append(f'| {name} | {tier} | {len(weeks)} | {weeks[0]} | {weeks[-1]} | {what} |')
        out += ['', '**Q-Schools** (a final\'s cards are for the next season, decided with the other cards at the '
                'season\'s end):', '',
                '| Stage | Week | Season its cards are for |', '|---|---|---|']
        cards = {'PT_QSCHOOL_FINAL': 'places 1-5: Premier Tour Americas; 6-45: Challenger Tour Americas',
                 'EU_QSCHOOL_FINAL': 'places 1-20: Premier Tour Europe; 21-60: Challenger Tour Europe',
                 'JP_QSCHOOL_FINAL': 'places 1-30: Japan Golf Tour', 'ASIA_QSCHOOL_FINAL': 'places 1-35: Asian Challenger Tour'}
        for sid, wk in sorted(sp.qschool.items(), key=lambda x: x[1]):
            gap = 52 - wk + 1
            when = (f'the next season (effective {gap} week{"s" if gap != 1 else ""} later)' if sid in sp.qschool_next_season
                    else 'the same season')
            if sid not in cards:
                when = 'a stage: its leading finishers go on to the next stage (it awards no cards itself)'
            if sid == 'ASIA_QSCHOOL_FINAL' and wk < 26:
                when = (f'the next season: played in week {wk}, its cards wait until the end of this season '
                        f'(effective {52 - wk + 1} weeks later)')
            out.append(f'| {sid}{" — " + cards[sid] if sid in cards else ""} | {wk} | {when} |')
        out += ['', '**Major cut-offs during the season** (each list read as published at the end of that week; '
                'before then the places it decides are pending):', '', '| Cut-off | Week |', '|---|---|']
        for k, wk in sp.cutoffs.items():
            out.append(f'| {k.replace("_", " ")} | {wk} |')
        names = WorldCalendar(YEAR, v).by_id
        maj = ', '.join(f'{names[sid].name} week {wk}' for sid, wk in sp.majors.items())
        out += ['', f'Majors: {maj}. USA Open final qualifying week {sp.usa_final}; Britannia Open final qualifying '
                f'week {sp.britannia_final}.', '']
        late = sorted((wk, k) for k, ws in mw.items() if k in TOUR_BY_KEY and TOUR_BY_KEY[k].tier <= 4
                      for wk in [ws[-1]] if wk >= 45)
        if late:
            out += [f'Card-deciding lists that lock in week 45 or later: '
                    + ', '.join(f'{TOUR_BY_KEY[k].name} (week {wk})' for wk, k in late) + '. Their results still '
                    'count for that season\'s cards, which are decided after week 52.', '']
    out += ['## Reconciled with the engine', '',
            '- The weeks above are read from the calendar the engine plays; the card numbers from `golfsim/cards.py`.',
            '- The classic calendar (`v1`) played the Asian Q-School final in week 2: its cards waited until the end '
            'of that season (51 weeks later). The reference calendar (`v2`) plays it in week 51, so its cards take '
            'effect a week later, like the other Q-Schools.',
            '- In-season Premier playing rights (full or conditional status at entry) come from the cards held at '
            'the start of the season and winners\' exemptions earned during it (an exemption counts from the week '
            'it is won).', '']
    return '\n'.join(out)


if __name__ == '__main__':
    sys.stdout.write(doc())
