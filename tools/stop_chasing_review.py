"""Review of the stop-chasing pressure (careers.p_stop_chasing) over a grid of scenarios.

    python tools/stop_chasing_review.py > reports/STOP_CHASING_REVIEW.md

For a typical 25-year-old full-time professional (median work ethic and big-stage appetite, healthy), on a
mini tour and on a Challenger tour, the chance they stop chasing this winter for combinations of:
    money        their own cash (no family money, no backers), from deep debt to a fortune
    progress     none (ranking flat), moderate (ranking up by half, two top-10s), strong (a win, promotion)
    opportunity  none, a place already secured in a major
It also shows the rule before the last change (`1 - 2 * runway` for the broke term) beside the current
one (`1 - runway`), so the effect of that change is visible across the grid, not in one case.
"""
from __future__ import annotations

import copy
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from golfsim import careers as C                                      # noqa: E402
from golfsim.calendar import TOUR_BY_KEY                              # noqa: E402
from golfsim.population import generate_world                         # noqa: E402
from golfsim.season import Season                                     # noqa: E402

CASH = (-20000, 0, 10000, 30000, 60000, 150000, 1000000)
PROGRESS = {'none': {'wr_start': 400, 'wr_end': 400, 'wins': 0, 'top10': 0},
            'moderate': {'wr_start': 600, 'wr_end': 400, 'wins': 0, 'top10': 2},
            'strong': {'wr_start': 600, 'wr_end': 250, 'wins': 1, 'top10': 4, 'promoted': True}}
OPPORTUNITY = {'none': [], 'major place secured': ['USA Open: Top 10 and ties, last USA Open']}


def old_p(season, g, row, year):
    runway = C.runway_years(season, g, year, g.tour, season.target_events(g), row, own_money=True)
    x = -4.5 + 4.0 / (1 + runway) + 2.2 * max(0.0, 1 - 2 * runway) - C.desire_to_continue(season, g, row, year)
    return 1 / (1 + math.exp(-x))


def main():
    s = Season(generate_world(seed=11, scale=0.2), seed=11, development=True, workers=1)
    s.start_year(2027)
    s.year = 2027
    print('# Stop-chasing pressure: a grid review\n')
    print('Generated by `tools/stop_chasing_review.py` (current engine). Chance (%) that a 25-year-old full-time '
          'professional with median willingness stops chasing this winter; *old* = the rule before the broke '
          'term was widened (`1 - 2 x runway`), *now* = `1 - runway`. Runway = seasons their own money lasts.\n')
    for tier in (4, 2):
        base = next(g for g in s.active_golfers() if g.status == 'pro' and g.lifestyle == 'full_time'
                    and g.tour in TOUR_BY_KEY and TOUR_BY_KEY[g.tour].tier == tier)
        g = copy.deepcopy(base)
        g.born = 2027 - 25
        g.personality['work_ethic'] = g.personality['big_stage'] = 50.0
        g.backing = g.backer_funds = g.backer = 0.0
        s.prize_record[g.id] = {tier: [0.002, 20, 2027]}
        print(f'## {TOUR_BY_KEY[g.tour].name} (tier {tier})\n')
        print('| Cash | Progress | Opportunity | Runway | Desire | old % | now % |')
        print('|---|---|---|---|---|---|---|')
        for cash in CASH:
            g.cash = float(cash)
            for pn, pr in PROGRESS.items():
                for on, sec in OPPORTUNITY.items():
                    row = dict(pr, tier=tier, tour=g.tour, status='pro', lifestyle='full_time', secured=sec,
                               injury_weeks=0, prize_by_tier={tier: (5000.0, 20)}, prize=5000.0)
                    p, why = C.p_stop_chasing(s, g, row, 2027)
                    print(f'| ${cash:,} | {pn} | {on} | {why["runway"]:.2f} | {why["desire"]:+.2f} | '
                          f'{100 * old_p(s, g, row, 2027):.1f} | {100 * p:.1f} |')
        print()
    s.close()


if __name__ == '__main__':
    main()
