"""The before and after calendar manifest (roadmap v14): every series of the classic calendar (v1) and the
reference calendar (v2) side by side by stable series id -- week, day pattern, host country and city pool,
eligibility, tier and category -- with what changed, plus each major's qualification routes under both
versions and the cut-offs they read. Read-only: builds the two calendars from their specifications.

    python tools/calendar_manifest.py [--out docs/CALENDAR_MANIFEST.md]
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from golfsim import qualification as Q                                    # noqa: E402
from golfsim import schedule as SCH                                       # noqa: E402
from golfsim.calendar import WorldCalendar                                # noqa: E402


def _days(s):
    return s.days or {18: 'Sat', 36: 'Sat-Sun', 54: 'Fri-Sun', 72: 'Thu-Sun'}[s.holes]


def _row(s):
    return {'week': s.week, 'days': _days(s), 'country': s.host_country, 'cities': s.cities, 'elig': s.eligibility,
            'tier': s.tier, 'cat': s.category, 'name': s.name, 'field': s.field, 'holes': s.holes}


def manifest():
    old, new = WorldCalendar(2027, 'v1'), WorldCalendar(2027, 'v2')
    a = {s.series_id: _row(s) for s in old.series}
    b = {SCH.canonical(s.series_id): _row(s) for s in new.series}
    a = {SCH.canonical(k): v for k, v in a.items()}
    out = ['# Calendar manifest: classic (v1) and reference (v2)', '',
           f'Generated by `tools/calendar_manifest.py` from `golfsim/schedule.py`. {len(a)} series in v1, {len(b)} in '
           'v2, matched by stable series id (the qualifying waves were named by week in v1 and by wave in v2: '
           '`schedule.ALIASES` maps one onto the other). Weeks are the 52-week game season; days are the days of '
           'that week the event occupies. New worlds use v2; a world saved before calendar versions keeps v1 for '
           'good (no migration has been made or approved).', '']
    out += ['## The fixed structure', '', '| | v1 (classic) | v2 (reference) |', '|---|---|---|']
    for sid in ('TOUR_MASTERS', 'PREMIER_TOUR_CHAMPIONSHIP', 'USA_OPEN', 'BRITANNIA_OPEN'):
        out.append(f'| {a[sid]["name"]} | week {a[sid]["week"]} | week {b[sid]["week"]} |')
    sp1, sp2 = SCH.V1, SCH.V2
    out += [f'| Post-major opportunity weeks | {", ".join(map(str, sp1.opportunity_after_majors))} | '
            f'{", ".join(map(str, sp2.opportunity_after_majors))} |',
            f'| USA Open local qualifying | weeks {", ".join(str(w) for _, w, _ in sp1.usa_local)} (every applicant could '
            f'try each wave until entered) | waves in weeks {", ".join(str(w) for _, w, _ in sp2.usa_local)} (one '
            'chosen wave: one attempt) |',
            f'| USA Open final qualifying | international {sp1.usa_final_intl}, domestic {sp1.usa_final} | international '
            f'{sp2.usa_final_intl} (direct entries only), domestic {sp2.usa_final} |',
            f'| Britannia regional qualifying | weeks {", ".join(str(w) for _, w, _ in sp1.britannia_regional)} | '
            f'waves in weeks {", ".join(str(w) for _, w, _ in sp2.britannia_regional)} (one attempt across them) |',
            f'| Britannia final qualifying | week {sp1.britannia_final} | week {sp2.britannia_final} (Tuesday) |',
            f'| Club professionals | sectionals {sp1.anchors["CLUB_PRO_SECTIONALS"]}, championship '
            f'{sp1.anchors["CLUB_PRO_CHAMPIONSHIP"]} | sectionals {sp2.anchors["CLUB_PRO_SECTIONALS"]}, championship '
            f'{sp2.anchors["CLUB_PRO_CHAMPIONSHIP"]} (20 places in the week 20 major) |',
            f'| Asian Challenger Q-School | week {sp1.qschool["ASIA_QSCHOOL_FINAL"]} (cards for the season after) | '
            f'week {sp2.qschool["ASIA_QSCHOOL_FINAL"]} (cards for the next season) |',
            '| Annual amateur award | leading amateur in the week 26 ranking, for that season\'s Britannia Open | '
            'leading amateur after the USA Amateur (week 33), named in week 34: conditional places in next '
            'season\'s USA Open and Britannia Open |',
            f'| Majors spacing enforced | no | {sp2.major_spacing} weeks |',
            '| Day-level travel between events in one week | no (non-overlapping days only) | yes: none within a '
            'country, one free day within a region, two between regions |', '']
    prem1 = Counter((s.category if s.category != 'national_open' else 'standard') for s in old.series if s.tier == 1)
    prem2 = Counter((s.category if s.category != 'national_open' else 'standard') for s in new.series if s.tier == 1)
    out += [f'Premier events: v1 {dict(prem1)}, v2 {dict(prem2)} (8 flagship, 20 standard including national opens, '
            '8 opportunity in both).', '']
    out += ['## Premier Tour: the 36 events', '', '| Series | Category | v1 week | v2 week | v2 hosts |', '|---|---|---|---|---|']
    for sid in sorted((k for k, v in b.items() if v['tier'] == 1), key=lambda k: (b[k]['week'], k)):
        x, y = a.get(sid), b[sid]
        out.append(f'| {y["name"]} (`{sid}`) | {y["cat"]} | {x["week"] if x else "—"} | **{y["week"]}** |'
                   f' {", ".join(y["cities"][:5])}{" …" if len(y["cities"]) > 5 else ""} |')
    out += ['', '## Every other series that changed', '', '| Series | Tier | v1 | v2 | What changed |', '|---|---|---|---|---|']
    changed = 0
    for sid in sorted(set(a) | set(b), key=lambda k: (b.get(k, a.get(k))['tier'], k)):
        x, y = a.get(sid), b.get(sid)
        if y and y['tier'] == 1:
            continue
        if x is None or y is None:
            out.append(f'| `{sid}` | {(x or y)["tier"]} | {"—" if x is None else x["week"]} | {"—" if y is None else y["week"]} '
                       f'| {"new" if x is None else "removed"} |')
            changed += 1
            continue
        diff = [k for k in ('week', 'days', 'country', 'cities', 'elig', 'field', 'holes', 'cat') if x[k] != y[k]]
        if x['name'] != y['name'] and sid not in SCH.ALIASES.values():
            diff.append('name')
        if not diff:
            continue
        changed += 1
        what = []
        for k in diff:
            if k == 'cities':
                what.append(f'host cities {", ".join(x["cities"][:3])}… → {", ".join(y["cities"][:3])}…')
            elif k == 'week':
                what.append(f'week {x["week"]} → {y["week"]}')
            else:
                what.append(f'{k} {x[k]} → {y[k]}')
        out.append(f'| {y["name"]} (`{sid}`) | {y["tier"]} | {x["week"]} | {y["week"]} | {"; ".join(what)} |')
    out += ['', f'{changed} non-Premier series changed (week, days, hosts, eligibility or format); every other series '
            'is identical in both versions. Local amateur, club professional, mini, regional and Challenger events '
            'are placed by the same generator around the fixed structure, so some of them move to other weeks or '
            'hosts; their counts, fields, formats and country allocations are unchanged.', '']
    # lower tours keep playing in major weeks
    out += ['## Golf in the major weeks (v2)', '', '| Week | Major | Other events that week (by tier) |', '|---|---|---|']
    for w in sorted(new.major_weeks):
        tiers = Counter(s.tier for s in new.series if s.week == w and s.tier != 0)
        major = next(s.name for s in new.series if s.week == w and s.tier == 0)
        out.append(f'| {w} | {major} | ' + ', '.join(f'tier {t}: {n}' for t, n in sorted(tiers.items())) + ' |')
    # rules
    out += ['', '## Qualification routes by version', '',
            'Route codes are stable; a route marked *v2* is new or changed in the reference calendar. Cut-offs: v1 read '
            'the latest ranking on or before the cut-off week; v2 reads the snapshot published after exactly that week '
            '(a later or earlier list never stands in, and asking for one not yet published is an error).', '']
    r1, r2 = Q.rules_for('v1'), Q.rules_for('v2')
    for major in Q.MAJOR_SERIES:
        out += [f'### {a[major]["name"]}', '', '| Code | v1 | v2 |', '|---|---|---|']
        codes = list(dict.fromkeys([r.code for r in r1[major]] + [r.code for r in r2[major]]))
        by1, by2 = {r.code: r for r in r1[major]}, {r.code: r for r in r2[major]}
        for c in codes:
            l1 = by1[c].label if c in by1 else '—'
            l2 = by2[c].label if c in by2 else '—'
            mark = ' *v2*' if l1 != l2 else ''
            out.append(f'| {c} | {l1} | {l2}{mark} |')
        out.append('')
    out += ['## Cut-off weeks', '', '| Cut-off | v1 week | v2 week |', '|---|---|---|']
    for k in dict.fromkeys(list(SCH.V1.cutoffs) + list(SCH.V2.cutoffs)):
        out.append(f'| {k} | {SCH.V1.cutoffs.get(k, "—")} | {SCH.V2.cutoffs.get(k, "—")} |')
    errs = {'v1': old.validate(), 'v2': new.validate()}
    out += ['', '## Validation', '', *[f'- {v}: {len(e)} problems' + (': ' + '; '.join(e[:5]) if e else '')
                                     for v, e in errs.items()], '']
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out')
    a = ap.parse_args()
    text = manifest()
    if a.out:
        Path(a.out).write_text(text)
    print(text[:3000])


if __name__ == '__main__':
    main()
